#ifndef HAL_LCD_I2C_LCD_I2C_PRV_H_
#define HAL_LCD_I2C_LCD_I2C_PRV_H_


/* =========================================
 * LCD DDRAM Addresses
 * ========================================= */

/* First Row */
#define DDRAM_BASE_ADDR_R0      0x80

/* Second Row */
#define DDRAM_BASE_ADDR_R1      0xC0


/* =========================================
 * LCD CGRAM Address
 * ========================================= */

#define CGRAM_BASE_ADDR         0x40


/* =========================================
 * LCD Mode
 * ========================================= */

#define LCD_I2C_4BIT_MODE       0x02


#endif /* HAL_LCD_I2C_LCD_I2C_PRV_H_ */
